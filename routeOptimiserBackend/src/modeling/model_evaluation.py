# src/modeling/model_evaluation.py
"""
Evaluation of the Disaster Prediction Engine — what the model can and cannot be claimed to do.

The project brief is explicit that the flood and landslide forests "have not been evaluated
using a train/test split, cross-validation, or documented performance metrics". This module is
that evaluation, and it is careful about what it measures.

Three questions, three answers
------------------------------
1. **Does the pipeline learn what it was shown?**  Held-out split + stratified k-fold
   cross-validation on the synthetic data, with ROC-AUC, Brier score, log-loss, precision,
   recall and a calibration table. Compared against two reference points:
     * a no-skill baseline that always predicts the training prevalence, and
     * the *oracle* — the rule that generated the labels. Labels are Bernoulli draws from
       that rule, so no model can beat it; the gap to it is how much of the learnable signal
       the forest actually captured.
   This measures the pipeline. It says NOTHING about real-world accuracy, because the labels
   are our own rules, and every report produced here says so.

2. **What happens outside the training range?**  The Pan-India network reaches 5,300 m and
   extreme rainfall the synthetic set never contained. The same rules label a sample drawn
   from those wider ranges and the frozen model is scored on it — quantifying the degradation
   the API flags as `out_of_training_domain`.

3. **How would it do on real events?**  `evaluate_on_events()` takes a CSV of real, labelled
   corridor-days (GSI landslide inventory, CWC/ASDMA flood records joined to IMD rainfall) and
   scores the deployed model on it. No such file ships with the repository — that is the
   honest state of the project — but the harness is ready for one.

Deterministic: fixed seeds throughout, so every number in a report can be reproduced.
"""

from __future__ import annotations

import csv
import json
import math
import os
import random
from datetime import datetime, timezone

from src.modeling.disaster_prediction import (
    FEATURE_NAMES,
    TRAINING_SAMPLES,
    TRAINING_SEED,
    _flood_latent,
    _landslide_latent,
    _sigmoid,
    generate_training_data,
)

EVALUATION_SEED = 20260930
TEST_FRACTION = 0.25
CV_FOLDS = 5
CALIBRATION_BINS = 10

# Same hyper-parameters as the deployed forests (disaster_prediction.RandomForestDisasterPredictor).
FOREST_PARAMS = dict(n_estimators=120, max_depth=8, min_samples_leaf=10, random_state=TRAINING_SEED)

EVALUATION_PATH = os.path.abspath(os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "..", "data", "processed", "model_evaluation.json"
))

SYNTHETIC_CAVEAT = (
    "Scored against held-out SYNTHETIC labels generated by the project's own rules. This shows "
    "the pipeline learns the rules it was given; it is not evidence of real-world predictive "
    "accuracy, and must not be presented as such."
)

# Wider ranges seen on the Pan-India network (high passes, extreme monsoon days).
PAN_INDIA_RANGES = {
    "rainfall_mm_24h": (0, 400),
    "forecast_rainfall_mm_48h": (0, 450),
    "slope_gradient_deg": (0, 35),
    "elevation_m": (0, 5500),
    "historical_landslides_5y": (0, 20),
    "historical_floods_5y": (0, 14),
    "road_vulnerability_index": (10, 95),
    "recent_incident_count": (0, 6),
}


# ---------------------------------------------------------------- metrics (dependency-light)


def _roc_auc(y, p) -> float | None:
    """Mann-Whitney formulation; ties get half credit. None when only one class is present."""
    pos = [pi for yi, pi in zip(y, p) if yi == 1]
    neg = [pi for yi, pi in zip(y, p) if yi == 0]
    if not pos or not neg:
        return None
    ranked = sorted([(v, 1) for v in pos] + [(v, 0) for v in neg])
    # average ranks for ties
    ranks, i = {}, 0
    rank_sum_pos = 0.0
    while i < len(ranked):
        j = i
        while j < len(ranked) and ranked[j][0] == ranked[i][0]:
            j += 1
        avg = (i + 1 + j) / 2.0
        rank_sum_pos += avg * sum(1 for k in range(i, j) if ranked[k][1] == 1)
        i = j
    n_pos, n_neg = len(pos), len(neg)
    return (rank_sum_pos - n_pos * (n_pos + 1) / 2.0) / (n_pos * n_neg)


def _brier(y, p) -> float:
    return sum((pi - yi) ** 2 for yi, pi in zip(y, p)) / len(y)


def _log_loss(y, p) -> float:
    eps = 2.220446049250313e-16  # float64 machine epsilon, as scikit-learn clips
    return -sum(yi * math.log(max(eps, pi)) + (1 - yi) * math.log(max(eps, 1 - pi))
                for yi, pi in zip(y, p)) / len(y)


def _threshold_metrics(y, p, threshold=0.5) -> dict:
    tp = sum(1 for yi, pi in zip(y, p) if pi >= threshold and yi == 1)
    fp = sum(1 for yi, pi in zip(y, p) if pi >= threshold and yi == 0)
    fn = sum(1 for yi, pi in zip(y, p) if pi < threshold and yi == 1)
    tn = sum(1 for yi, pi in zip(y, p) if pi < threshold and yi == 0)
    precision = tp / (tp + fp) if tp + fp else None
    recall = tp / (tp + fn) if tp + fn else None
    f1 = (2 * precision * recall / (precision + recall)) if precision and recall else None
    return {
        "threshold": threshold,
        "accuracy": round((tp + tn) / len(y), 4),
        "precision": None if precision is None else round(precision, 4),
        "recall": None if recall is None else round(recall, 4),
        "f1": None if f1 is None else round(f1, 4),
        "confusion": {"tp": tp, "fp": fp, "fn": fn, "tn": tn},
    }


def _calibration(y, p, bins=CALIBRATION_BINS) -> list:
    out = []
    for b in range(bins):
        lo, hi = b / bins, (b + 1) / bins
        idx = [i for i, pi in enumerate(p) if lo <= pi < hi or (b == bins - 1 and pi == 1.0)]
        if not idx:
            continue
        out.append({
            "bin": f"{lo:.1f}-{hi:.1f}",
            "count": len(idx),
            "mean_predicted": round(sum(p[i] for i in idx) / len(idx), 4),
            "observed_rate": round(sum(y[i] for i in idx) / len(idx), 4),
        })
    return out


def score(y, p) -> dict:
    """Every metric for one set of labels and probabilities."""
    auc = _roc_auc(y, p)
    prevalence = sum(y) / len(y)
    return {
        "n": len(y),
        "prevalence": round(prevalence, 4),
        "roc_auc": None if auc is None else round(auc, 4),
        "brier": round(_brier(y, p), 4),
        "brier_no_skill": round(prevalence * (1 - prevalence), 4),
        "log_loss": round(_log_loss(y, p), 4),
        **_threshold_metrics(y, p),
        "calibration": _calibration(y, p),
    }


# ---------------------------------------------------------------- splitting


def _stratified_split(y, test_fraction, seed):
    rng = random.Random(seed)
    test = set()
    for cls in (0, 1):
        idx = [i for i, v in enumerate(y) if v == cls]
        rng.shuffle(idx)
        test.update(idx[: int(round(len(idx) * test_fraction))])
    train = [i for i in range(len(y)) if i not in test]
    return train, sorted(test)


def _stratified_folds(y, k, seed):
    rng = random.Random(seed)
    folds = [[] for _ in range(k)]
    for cls in (0, 1):
        idx = [i for i, v in enumerate(y) if v == cls]
        rng.shuffle(idx)
        for n, i in enumerate(idx):
            folds[n % k].append(i)
    return folds


def _oracle_probabilities(X, target: str) -> list:
    latent = _flood_latent if target == "flood" else _landslide_latent
    return [_sigmoid(latent(dict(zip(FEATURE_NAMES, row)))) for row in X]


def _fit(X, y):
    from sklearn.ensemble import RandomForestClassifier

    return RandomForestClassifier(**FOREST_PARAMS).fit(X, y)


def _positive(model, X) -> list:
    classes = list(model.classes_)
    col = classes.index(1) if 1 in classes else len(classes) - 1
    return [float(row[col]) for row in model.predict_proba(X)]


# ---------------------------------------------------------------- evaluations


def _sample_wide(n, seed) -> tuple:
    """Pan-India-range features labelled by the same rules (out-of-distribution check)."""
    rng = random.Random(seed)
    X, y_flood, y_slide = [], [], []
    for _ in range(n):
        f = {k: rng.uniform(*PAN_INDIA_RANGES[k]) for k in FEATURE_NAMES}
        X.append([f[k] for k in FEATURE_NAMES])
        y_flood.append(1 if rng.random() < _sigmoid(_flood_latent(f)) else 0)
        y_slide.append(1 if rng.random() < _sigmoid(_landslide_latent(f)) else 0)
    return X, y_flood, y_slide


def evaluate_synthetic(n_samples: int = TRAINING_SAMPLES, folds: int = CV_FOLDS,
                       test_fraction: float = TEST_FRACTION) -> dict:
    """Held-out, cross-validated and out-of-range evaluation of both forests."""
    X, y_flood, y_slide = generate_training_data(n_samples=n_samples, seed=TRAINING_SEED)
    X_wide, yw_flood, yw_slide = _sample_wide(max(500, n_samples // 4), EVALUATION_SEED + 7)

    report = {}
    for target, y, y_wide in (("flood", y_flood, yw_flood), ("landslide", y_slide, yw_slide)):
        train, test = _stratified_split(y, test_fraction, EVALUATION_SEED)
        model = _fit([X[i] for i in train], [y[i] for i in train])
        X_test, y_test = [X[i] for i in test], [y[i] for i in test]
        p_test = _positive(model, X_test)

        cv = []
        for k, fold in enumerate(_stratified_folds(y, folds, EVALUATION_SEED + 1)):
            held = set(fold)
            fold_model = _fit([X[i] for i in range(len(y)) if i not in held],
                              [y[i] for i in range(len(y)) if i not in held])
            p = _positive(fold_model, [X[i] for i in fold])
            yk = [y[i] for i in fold]
            cv.append({"fold": k + 1, "roc_auc": round(_roc_auc(yk, p), 4), "brier": round(_brier(yk, p), 4)})
        aucs = [c["roc_auc"] for c in cv]
        mean = sum(aucs) / len(aucs)
        std = math.sqrt(sum((a - mean) ** 2 for a in aucs) / len(aucs))

        # Frozen model (trained on the NER-range split) scored on Pan-India ranges.
        p_wide = _positive(model, X_wide)

        report[target] = {
            "holdout": score(y_test, p_test),
            "oracle_holdout": score(y_test, _oracle_probabilities(X_test, target)),
            "cross_validation": {
                "folds": cv,
                "roc_auc_mean": round(mean, 4),
                "roc_auc_std": round(std, 4),
            },
            "out_of_training_range": {
                "description": "Frozen model on features drawn from Pan-India ranges "
                               "(elevation to 5,500 m, rain to 400 mm/24 h), same labelling rules.",
                "model": score(y_wide, p_wide),
                "oracle": score(y_wide, _oracle_probabilities(X_wide, target)),
            },
        }

    return {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "data": "synthetic",
        "samples": n_samples,
        "test_fraction": test_fraction,
        "cv_folds": folds,
        "seeds": {"training": TRAINING_SEED, "evaluation": EVALUATION_SEED},
        "hyperparameters": FOREST_PARAMS,
        "caveat": SYNTHETIC_CAVEAT,
        "targets": report,
        "interpretation": interpret(report),
    }


def interpret(report: dict) -> list:
    """Plain-language reading of the numbers, generated from them rather than written by hand."""
    lines = []
    for target, r in report.items():
        h, o = r["holdout"], r["oracle_holdout"]
        lines.append(
            f"{target.capitalize()}: held-out ROC-AUC {h['roc_auc']:.3f} against an oracle ceiling "
            f"of {o['roc_auc']:.3f}; Brier {h['brier']:.3f} vs {h['brier_no_skill']:.3f} for a "
            f"no-skill forecast. Cross-validated AUC {r['cross_validation']['roc_auc_mean']:.3f} "
            f"± {r['cross_validation']['roc_auc_std']:.3f}."
        )
        wide = r["out_of_training_range"]
        lines.append(
            f"{target.capitalize()} outside the training range: AUC {wide['model']['roc_auc']:.3f} "
            f"(oracle {wide['oracle']['roc_auc']:.3f}), Brier {wide['model']['brier']:.3f} "
            f"(oracle {wide['oracle']['brier']:.3f}) — the gap is what extrapolation costs."
        )
    lines.append(SYNTHETIC_CAVEAT)
    return lines


def evaluate_on_events(csv_path: str, predictor=None) -> dict:
    """Score the deployed predictor on REAL labelled events.

    CSV columns: every name in FEATURE_NAMES, plus `flood_event` and/or `landslide_event`
    (0/1). One row per corridor-day. This is the evaluation that would support a real-world
    accuracy claim; nothing in the repository supplies such a file yet.
    """
    from src.modeling.disaster_prediction import get_default_predictor

    predictor = predictor or get_default_predictor()
    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(line for line in f if not line.lstrip().startswith("#")))
    if not rows:
        raise ValueError("No rows in events file")
    missing = [n for n in FEATURE_NAMES if n not in rows[0]]
    if missing:
        raise ValueError(f"Events file is missing feature columns: {missing}")

    predictions = predictor.predict_many([{n: row[n] for n in FEATURE_NAMES} for row in rows])
    out = {"data": "real events", "source_file": os.path.basename(csv_path), "rows": len(rows),
           "model_type": predictions[0].model_type, "targets": {}}
    for target, column, attr in (("flood", "flood_event", "flood_probability"),
                                 ("landslide", "landslide_event", "landslide_probability")):
        if column not in rows[0]:
            continue
        y = [int(float(r[column])) for r in rows]
        p = [getattr(pr, attr) for pr in predictions]
        out["targets"][target] = score(y, p)
    return out


def load_or_evaluate(path: str = EVALUATION_PATH, refresh: bool = False) -> dict:
    """The stored report if present (it takes ~20 s to regenerate), else compute and store it."""
    if not refresh and os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    report = evaluate_synthetic()
    try:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            json.dump(report, f, indent=2)
    except OSError:
        pass
    return report
